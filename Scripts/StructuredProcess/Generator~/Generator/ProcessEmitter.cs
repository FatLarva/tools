using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Tools.StructuredProcess.Generator
{
    internal sealed class ProcessEmitter
    {
        private const string Runtime = "global::" + Names.Runtime;
        private readonly StringBuilder _source = new StringBuilder();
        private int _indent;

        internal static string Emit(ProcessModel process)
        {
            var emitter = new ProcessEmitter();
            emitter.WriteProcess(process);
            return emitter._source.ToString();
        }

        private void WriteProcess(ProcessModel process)
        {
            Line("// <auto-generated />");
            Line("#nullable disable");
            bool hasNamespace = !process.Type.ContainingNamespace.IsGlobalNamespace;
            if (hasNamespace)
            {
                Open("namespace " + process.Type.ContainingNamespace.ToDisplayString());
            }

            Open("partial class @" + process.Type.Name);
            Line("private readonly Input __processInput;");
            Line();
            Open("public struct Input : " + Runtime + "IProcessInput");
            foreach (var input in process.Inputs.OrderBy(item => item.Name, System.StringComparer.Ordinal))
            {
                if (input.Label != null)
                {
                    Line("[" + Runtime + "Data(" + Literal(input.Label) + ")]");
                }

                Line("public " + Names.Full(input.Type) + " @" + input.Name + ";");
            }

            Close();
            Line();
            Open("public @" + process.Type.Name + "(Input input, global::Logging.ILog logger = null) : base(logger)");
            Line("__processInput = input;");
            Close();
            Line();

            string result = Runtime + "StepResult<Output>";
            string signature = "public " + (process.Order.Count == 0 ? "" : "async ")
                + "global::System.Threading.Tasks.ValueTask<" + result
                + "> ExecuteAsync(global::System.Threading.CancellationToken cancellationToken = default)";
            Open(signature);
            Line("cancellationToken.ThrowIfCancellationRequested();");
            foreach (var step in process.Order)
            {
                WriteStep(step, process);
            }

            Line("cancellationToken.ThrowIfCancellationRequested();");
            string prefix = process.Order.Count == 0
                ? "return new global::System.Threading.Tasks.ValueTask<" + result + ">(" : "return ";
            Line(prefix + result + ".Success(new Output");
            Line("{");
            _indent++;
            foreach (var binding in process.OutputBindings)
            {
                Line("@" + binding.Target.Name + " = " + Value(binding) + ",");
            }

            _indent--;
            Line(process.Order.Count == 0 ? "}));" : "});");
            Close();
            Close();
            if (hasNamespace)
            {
                Close();
            }
        }

        private void WriteStep(StepModel step, ProcessModel process)
        {
            string number = step.Index.ToString(System.Globalization.CultureInfo.InvariantCulture);
            string variable = "result" + number;
            string resultType = Runtime + "StepResult<" + Names.Full(step.OutputType) + ">";
            string id = step.Id == null ? "typeof(" + Names.Full(step.Type) + ")" : Literal(step.Id);
            Line();
            Line("// " + (step.AnyThread ? "Any thread permitted; executed sequentially here." : "Main thread."));
            Line(resultType + " " + variable + ";");
            Line("cancellationToken.ThrowIfCancellationRequested();");
            Open("try");
            Line("var step" + number + " = new " + Names.Full(step.Type) + "(new " + Names.Full(step.InputType));
            Line("{");
            _indent++;
            foreach (var binding in step.Bindings)
            {
                Line("@" + binding.Target.Name + " = " + Value(binding) + ",");
            }

            _indent--;
            Line("});");
            Line(variable + " = await step" + number + ".ExecuteAsync(cancellationToken);");
            Close();
            Open("catch (global::System.OperationCanceledException) when (cancellationToken.IsCancellationRequested)");
            Line("throw;");
            Close();
            Open("catch (global::System.Exception exception)");
            Line(variable + " = " + resultType + ".Failure(exception);");
            Close();
            Line("cancellationToken.ThrowIfCancellationRequested();");
            Open("if (!" + variable + ".IsSuccess)");
            Line("ReportStepFailure(" + id + ", " + variable + ".Error, " + variable + ".Exception);");
            if (!step.Optional)
            {
                Line("return " + Runtime + "StepResult<Output>.Failure(" + variable + ".Error, " + variable + ".Exception);");
            }

            Close();
            if (process.OutputBindings.Any(binding => binding.Producer == step)
                || process.Steps.Any(item => item.Bindings.Any(binding => binding.Producer == step)))
            {
                Line("var output" + number + " = " + variable + ".Output;");
            }
        }

        private static string Value(Binding binding)
        {
            if (binding.External != null)
            {
                return "__processInput.@" + binding.External.Name;
            }

            return "output" + binding.Producer!.Index.ToString(System.Globalization.CultureInfo.InvariantCulture)
                + ".@" + binding.Output!.Name;
        }

        private static string Literal(string value)
        {
            return SymbolDisplay.FormatLiteral(value, true);
        }

        private void Open(string declaration)
        {
            Line(declaration);
            Line("{");
            _indent++;
        }

        private void Close()
        {
            _indent--;
            Line("}");
        }

        private void Line(string value = "")
        {
            if (value.Length != 0)
            {
                _source.Append(' ', _indent * 4);
            }

            _source.AppendLine(value);
        }
    }
}
